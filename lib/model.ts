// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks protocols that record no token. It covers every slug on the
// snapshot's watchlist (the floor, never a ceiling) and adds every pre-token
// protocol below the floor that passes the watchlist's own exclusion rule:
// no exchange, no bridge, no liquid-staking or restaking wrapper, no versioned
// pool name, no name carrying "wrapped", "staked" or "staking", no name
// beginning with an exchange's name. A wrapped product of a token that already
// trades is a bad airdrop subject, on the floor or below it.
//
// Implied value follows only from the snapshot's own figures:
//
//   multiple   = median(mcap_usd / tvl_usd) over the snapshot's live-token
//                protocols (computed at run time, never a hardcoded number):
//                what the market itself pays for a dollar of TVL.
//   growth     = clamp(change_7d, -50, 100) per cent (0 when unreported)
//   growthMult = 1 + (growth / 100) x 0.75
//   maturity   = 0.7 + 0.5 x min(age_days, 1095) / 1095
//                (age_days unknown: 365; age is the time since DefiLlama
//                began tracking the protocol, the best record of how long
//                it has run with no token)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard recomputes every row from the same figures in the page.

/** One protocol entry of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  /** Median mcap/TVL of the snapshot's live-token protocols, computed at run time. */
  base_multiple: number;
  /** How many live-token protocols the median came from. */
  multiple_sample: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL_VERSION = 'radar-2';

/** The fixed constants; base_multiple and multiple_sample are filled in at run time. */
export const MODEL: Omit<ModelConstants, 'base_multiple' | 'multiple_sample'> = {
  growth_weight: 0.75,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.5,
  maturity_days: 1095,
  unknown_age_days: 365,
};

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** One row of board.json. */
export interface BoardRow {
  rank: number;
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
  token_status: 'pre-token';
  watchlist: boolean;
  age_days: number | null;
  implied_value_usd: number;
  model: {
    base_multiple: number;
    growth_pct: number;
    growth_multiplier: number;
    maturity_multiplier: number;
    age_days: number | null;
  };
  farm_steps: string[];
}

